// Build once from canonical engines; --check verifies the committed bundle
// without repeating the multi-year calculation. No packages or network needed.
import { readFile, writeFile, mkdir, rename, readdir, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const MANIFEST_PATH = 'assets/data/horizon-2031-manifest.json';
const PART_DIRECTORY = 'assets/data/horizon-2031';
const VERSION_PATH = 'assets/js/core/data/horizon-preset-version.js';
const GRAPH_ROOTS = ['assets/js/core/event-horizon.js', 'assets/js/core/data/horizon-tool-coverage.js'];
const MAX_MANIFEST_BYTES = 1024 * 1024, MAX_PART_BYTES = 32 * 1024 * 1024, MAX_TOTAL_BYTES = 64 * 1024 * 1024;
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const jsonDigest = value => digest(JSON.stringify(value));
const compact = value => Buffer.from(JSON.stringify(value) + '\n');
const fail = message => { throw new Error(message); };
const plain = value => value && typeof value === 'object' && !Array.isArray(value);
const clone = value => JSON.parse(JSON.stringify(value));

// The built-in parser exposes actual static dependencies; it does not mistake
// a comment, string or import.meta for an import and executes no application code.
// The experimental flag is isolated to this parser subprocess so callers use
// `node scripts/generate-horizon-preset.mjs` without any special Node flags.
const GRAPH_PROGRAM = String.raw`
import vm from 'node:vm';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
const config=JSON.parse(process.argv[1]),root=path.resolve(config.root),seen=new Set(),external=new Set(),queue=[...config.roots],files=[];
while(queue.length){
 const relative=queue.shift();if(relative===config.exclude||seen.has(relative))continue;seen.add(relative);
 const absolute=path.resolve(root,relative);if(!absolute.startsWith(root+path.sep))throw new Error('Source import escapes the repository: '+relative);
 const bytes=fs.readFileSync(absolute),module=new vm.SourceTextModule(bytes.toString('utf8'),{identifier:pathToFileURL(absolute).href});
 files.push({path:relative,sha256:createHash('sha256').update(bytes).digest('hex')});
 for(const specifier of module.dependencySpecifiers){
  if(!specifier.startsWith('.')){external.add(relative+' -> '+specifier);continue;}
  const resolved=fileURLToPath(new URL(specifier,pathToFileURL(absolute))),next=path.relative(root,resolved).split(path.sep).join('/');
  if(next.startsWith('../')||path.isAbsolute(next))throw new Error('Source import escapes the repository: '+specifier);
  queue.push(next);
 }
}
files.sort((a,b)=>a.path<b.path?-1:a.path>b.path?1:0);
process.stdout.write(JSON.stringify({files,externalImports:[...external].sort()}));
`;

export function collectHorizonSourceBinding() {
  const child = spawnSync(process.execPath, ['--experimental-vm-modules', '--no-warnings', '--input-type=module', '-e', GRAPH_PROGRAM,
    JSON.stringify({ root: ROOT, roots: GRAPH_ROOTS, exclude: VERSION_PATH })], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
  if (child.error || child.status !== 0) fail(`Cannot parse the horizon source graph: ${child.error?.message || child.stderr}`);
  const parsed = JSON.parse(child.stdout);
  if (parsed.externalImports.length) fail('Unbound non-relative source imports need an explicit review: ' + parsed.externalImports.join(', '));
  return { algorithm: 'sha256-sorted-path-content-v1', roots: [...GRAPH_ROOTS], excluded: [VERSION_PATH], files: parsed.files, sha256: jsonDigest(parsed.files) };
}

function catalogueHashes(metadata, toolCoverage) {
  return { sourcesSHA256: jsonDigest(metadata.sources), coverageSHA256: jsonDigest(metadata.coverage), toolCoverageSHA256: jsonDigest(toolCoverage) };
}
function versionText(source, metadata, manifest) {
  return '// Generated by scripts/generate-horizon-preset.mjs. Do not edit by hand.\n' +
    '// Excluded from its own transitive source fingerprint to avoid a hash cycle.\n' +
    `export const HORIZON_PRESET_SOURCE_SHA256 = '${source}';\n` +
    `export const HORIZON_PRESET_METADATA_SHA256 = '${metadata}';\n` +
    `export const HORIZON_PRESET_MANIFEST_SHA256 = '${manifest}';\n`;
}
function readVersionText(text) {
  const result = {};
  for (const key of ['SOURCE', 'METADATA', 'MANIFEST']) {
    const found = text.match(new RegExp(`export const HORIZON_PRESET_${key}_SHA256 = '([a-f0-9]{64}|unbuilt)';`));
    if (!found) fail('Invalid generated horizon version module.');
    result[key.toLowerCase()] = found[1];
  }
  return result;
}
function same(a, b, message) { try { assert.deepEqual(a, b); } catch { fail(message); } }
function dateGrid(request) {
  const start = Date.parse(request.startDate + 'T12:00:00Z'), end = Date.parse(request.endDate + 'T12:00:00Z');
  if (!(Number.isFinite(start) && Number.isFinite(end) && end >= start)) fail('Invalid preset date range.');
  return Array.from({ length: Math.round((end - start) / 86400000) + 1 }, (_, i) => new Date(start + i * 86400000).toISOString().slice(0, 10));
}

// Pure integrity/coverage check. It consumes committed bytes, not ephemerides.
export function verifyHorizonBundle({ manifestBytes, partBytes, version, sourceBinding, expectedRequest, toolCoverage }) {
  if (manifestBytes.length > MAX_MANIFEST_BYTES) fail('Preset manifest exceeds 1 MiB.');
  if (digest(manifestBytes) !== version.manifest) fail('Preset manifest bytes do not match the generated version.');
  const manifest = JSON.parse(manifestBytes.toString('utf8'));
  if (manifest.kind !== 'event-horizon-preset' || manifest.schemaVersion !== 1) fail('Unsupported preset manifest.');
  if (!plain(manifest.metadata) || !Array.isArray(manifest.metadata.sources) || !plain(manifest.metadata.coverage)) fail('Preset metadata/source catalogue is absent.');
  same(manifest.request, expectedRequest, 'Preset does not contain the exact default complete request.');
  same(manifest.sourceBinding, sourceBinding, 'Preset is stale against the transitive source graph. Regenerate after source changes.');
  if (manifest.sourceBinding.sha256 !== version.source || jsonDigest(manifest.sourceBinding.files) !== version.source) fail('Preset source binding/version mismatch.');
  if (jsonDigest(manifest.metadata) !== version.metadata) fail('Preset metadata does not match the generated version.');
  same(manifest.catalogueHashes, catalogueHashes(manifest.metadata, toolCoverage), 'Preset source/coverage catalogue hashes disagree.');
  if (typeof manifest.datasetId !== 'string' || !/^horizon-2031-[a-f0-9]{12}-[a-f0-9]{12}$/.test(manifest.datasetId) || manifest.datasetId !== `horizon-2031-${version.source.slice(0, 12)}-${version.metadata.slice(0, 12)}`) fail('Preset dataset identity does not bind this source and metadata.');
  const dates = dateGrid(expectedRequest), expectedPartIds = [...expectedRequest.cases.map(c => 'case-' + c.id), 'astronomy'];
  if (!Array.isArray(manifest.parts) || manifest.parts.length !== expectedPartIds.length) fail('Preset parts are incomplete.');
  same(manifest.parts.map(p => p.id), expectedPartIds, 'Preset part IDs/order differ from the explicit cases.');
  if (new Set(manifest.parts.map(p => p.path)).size !== manifest.parts.length) fail('Duplicate preset part paths.');
  const loaded = new Map(); let totalBytes = manifestBytes.length;
  for (const part of manifest.parts) {
    if (part.path !== `horizon-2031/${part.id}.json` || !/^(?:case-[a-z][a-z0-9-]*|astronomy)$/.test(part.id)) fail('Unsafe or mismatched preset part path.');
    if (!Number.isInteger(part.bytes) || part.bytes < 1 || part.bytes > MAX_PART_BYTES || !/^[a-f0-9]{64}$/.test(part.sha256)) fail('Invalid bounded part descriptor.');
    const bytes = partBytes.get(part.path); if (!Buffer.isBuffer(bytes) || bytes.length !== part.bytes || digest(bytes) !== part.sha256) fail('Preset part byte length or checksum mismatch: ' + part.id);
    totalBytes += bytes.length; if (totalBytes > MAX_TOTAL_BYTES) fail('Preset exceeds the 64 MiB total limit.');
    loaded.set(part.id, JSON.parse(bytes.toString('utf8')));
  }
  if (partBytes.size !== manifest.parts.length) fail('Unexpected extra part bytes supplied.');
  let availableSamples = 0, profileResults = 0, rankableProfileResults = 0, calendarRows = 0, availableCalendarRows = 0;
  const observations = [], allObservationIds = new Set();
  for (const expected of expectedRequest.cases) {
    const payload = loaded.get('case-' + expected.id), c = payload?.case;
    if (!plain(c) || !Array.isArray(c.rows) || !Array.isArray(payload.observances) || c.id !== expected.id || c.rows.length !== dates.length) fail('Preset case is incomplete.');
    same({ id: c.id, label: c.label, ...c.observer, sampleTime: c.sampleTime, disambiguation: c.disambiguation }, expected, 'Preset observer case differs from the request.');
    const caseObservationIds = new Set();
    for (const observation of payload.observances) {
      if (observation.caseId !== c.id || typeof observation.id !== 'string' || observation.id !== c.id + '::' + observation.originId || !dates.includes(observation.date) || allObservationIds.has(observation.id)) fail('Observance case/date/identity is invalid.');
      allObservationIds.add(observation.id); caseObservationIds.add(observation.id); observations.push(observation);
    }
    const referencedIds = new Set();
    c.rows.forEach((row, index) => {
      if (row.date !== dates[index] || row.caseId !== c.id || !['available', 'unavailable'].includes(row.status)) fail('A requested date is missing, duplicated or reordered.');
      if (!Array.isArray(row.calendars) || row.calendars.length !== 13 || new Set(row.calendars.map(x => x.id)).size !== 13) fail('A daily row lacks thirteen distinct calendar slots.');
      if (!Array.isArray(row.purposeResults) || row.purposeResults.length !== expectedRequest.purposeIds.length) fail('A daily row lacks all purpose results.');
      same(row.purposeResults.map(x => x.id), expectedRequest.purposeIds, 'Daily purpose IDs/order differ from the request.');
      if (row.status === 'available') { if (typeof row.sampleUTC !== 'string' || !Number.isFinite(Date.parse(row.sampleUTC))) fail('Available sample has no valid UTC instant.'); availableSamples++; }
      else if (row.sampleUTC !== null) fail('Unavailable sample invents an instant.');
      for (const purpose of row.purposeResults) {
        if (purpose.rankable) {
          if (!Number.isFinite(purpose.score) || !Number.isInteger(purpose.scoreNumerator) || !Number.isInteger(purpose.scoreDenominator) || purpose.scoreDenominator <= 0 || purpose.score !== 100 * purpose.scoreNumerator / purpose.scoreDenominator || purpose.observed !== purpose.total || purpose.missing?.length !== 0) fail('Ranked purpose has invalid or incomplete score accounting.');
          rankableProfileResults++;
        } else if (purpose.score !== null || purpose.scoreNumerator !== null) fail('Unavailable profile invents a score.');
      }
      if (!Array.isArray(row.observanceIds) || new Set(row.observanceIds).size !== row.observanceIds.length) fail('Invalid daily observance references.');
      for (const id of row.observanceIds) { if (!caseObservationIds.has(id) || referencedIds.has(id) || !payload.observances.some(o => o.id === id && o.date === row.date)) fail('Daily observance reference is missing or mismatched.'); referencedIds.add(id); }
      profileResults += row.purposeResults.length; calendarRows += row.calendars.length; availableCalendarRows += row.calendars.filter(x => x.status === 'available').length;
    });
    if (referencedIds.size !== caseObservationIds.size) fail('An observance is orphaned from its daily row.');
  }
  const astronomy = loaded.get('astronomy');
  if (!plain(astronomy) || !Array.isArray(astronomy.events) || !Array.isArray(astronomy.coverage) || !plain(astronomy.window)) fail('Astronomy part is incomplete.');
  const eventIds = new Set(); let previous = -Infinity;
  for (const event of astronomy.events) {
    const at = Date.parse(event.startUTC);
    if (!event.id || eventIds.has(event.id) || !Number.isFinite(at) || at < previous || at < Date.parse(astronomy.window.startUTC) || at >= Date.parse(astronomy.window.endUTC)) fail('Astronomy events have duplicate IDs, invalid order or an out-of-window root.');
    eventIds.add(event.id); previous = at;
  }
  const totalSamples = dates.length * expectedRequest.cases.length, counts = manifest.metadata.counts;
  const expectedCounts = { days: dates.length, cases: expectedRequest.cases.length, totalSamples, processedSamples: totalSamples, availableSamples, unavailableSamples: totalSamples - availableSamples, calendarRows, availableCalendarRows, profileResults, rankableProfileResults, observanceRows: observations.length, uniqueObservances: new Set(observations.map(o => o.originId)).size, eventCount: astronomy.events.length, truncated: false };
  same(counts, expectedCounts, 'Manifest counts disagree with the complete scientific ledger.');
  if (manifest.metadata.provenance?.runtime?.environment !== 'node' || !manifest.metadata.provenance.runtime.node || !manifest.metadata.provenance.runtime.icu || !Number.isFinite(Date.parse(manifest.metadata.provenance.generatedAt)) || manifest.metadata.provenance.privateBirthIncluded !== false || manifest.metadata.provenance.modelUsed !== false) fail('Actual generating runtime/provenance is missing.');
  return { pass: true, datasetId: manifest.datasetId, sourceFiles: sourceBinding.files.length, parts: manifest.parts.length, totalBytes, counts, runtime: manifest.metadata.provenance.runtime };
}

async function application() {
  const core = await import(pathToFileURL(path.join(ROOT, GRAPH_ROOTS[0])).href);
  const inventory = await import(pathToFileURL(path.join(ROOT, GRAPH_ROOTS[1])).href);
  return { core, toolCoverage: { tools: inventory.HORIZON_TOOL_COVERAGE, references: inventory.HORIZON_REFERENCE_CAPABILITY_COVERAGE } };
}
async function checkPreset() {
  const sourceBinding = collectHorizonSourceBinding(), { core, toolCoverage } = await application();
  const manifestBytes = await readFile(path.join(ROOT, MANIFEST_PATH)), manifest = JSON.parse(manifestBytes.toString('utf8'));
  const version = readVersionText(await readFile(path.join(ROOT, VERSION_PATH), 'utf8')), partBytes = new Map();
  for (const part of manifest.parts || []) {
    if (typeof part.path !== 'string' || !/^horizon-2031\/(?:case-[a-z][a-z0-9-]*|astronomy)\.json$/.test(part.path)) fail('Unsafe preset path.');
    partBytes.set(part.path, await readFile(path.join(ROOT, 'assets/data', part.path)));
  }
  const actualPartFiles = (await readdir(path.join(ROOT, PART_DIRECTORY))).filter(f => f.endsWith('.json')).sort();
  same(actualPartFiles, manifest.parts.map(p => path.basename(p.path)).sort(), 'Stale or missing part JSON files.');
  return verifyHorizonBundle({ manifestBytes, partBytes, version, sourceBinding, expectedRequest: core.normalizeHorizonRequest(core.HORIZON_DEFAULT_REQUEST), toolCoverage });
}
async function atomicWrite(relative, bytes) {
  const file = path.join(ROOT, relative); await mkdir(path.dirname(file), { recursive: true });
  const temporary = file + '.tmp-' + process.pid; await writeFile(temporary, bytes); await rename(temporary, file);
}
async function generatePreset() {
  const sourceBinding = collectHorizonSourceBinding(), { core, toolCoverage } = await application();
  const request = core.normalizeHorizonRequest(core.HORIZON_DEFAULT_REQUEST);
  if (request.mode !== 'optimized' || request.cases.length !== 3 || request.purposeIds.length !== 4 || !request.includeAstronomy || !request.includeObservances) fail('Default horizon completeness contract changed; review the generator.');
  let lastReport = 0;
  const result = await core.buildEventHorizon(request, { onProgress: progress => {
    const at = Date.now(); if (at - lastReport >= 10000 || progress.phase === 'complete') { process.stderr.write(JSON.stringify({ phase: progress.phase, samples: progress.processedSamples, total: progress.totalSamples, astronomy: progress.astronomy }) + '\n'); lastReport = at; }
  } });
  core.validateHorizonLedger(result);
  same(collectHorizonSourceBinding(), sourceBinding, 'Source changed during generation; no preset files were written.');
  const { request: calculatedRequest, cases, observances, astronomy, ...metadata } = result;
  same(calculatedRequest, request, 'Canonical result changed its request.');
  const partBytes = new Map(), parts = [];
  for (const c of cases) {
    const id = 'case-' + c.id, relative = 'horizon-2031/' + id + '.json', bytes = compact({ case: c, observances: observances.filter(o => o.caseId === c.id) });
    partBytes.set(relative, bytes); parts.push({ id, path: relative, sha256: digest(bytes), bytes: bytes.length });
  }
  const astronomyBytes = compact(astronomy); partBytes.set('horizon-2031/astronomy.json', astronomyBytes); parts.push({ id: 'astronomy', path: 'horizon-2031/astronomy.json', sha256: digest(astronomyBytes), bytes: astronomyBytes.length });
  const metadataSHA256 = jsonDigest(metadata), datasetId = `horizon-2031-${sourceBinding.sha256.slice(0, 12)}-${metadataSHA256.slice(0, 12)}`;
  const manifest = { kind: 'event-horizon-preset', schemaVersion: 1, datasetId, request, sourceBinding, catalogueHashes: catalogueHashes(metadata, toolCoverage), parts, metadata };
  const manifestBytes = Buffer.from(JSON.stringify(manifest, null, 2) + '\n'), version = { source: sourceBinding.sha256, metadata: metadataSHA256, manifest: digest(manifestBytes) };
  const checked = verifyHorizonBundle({ manifestBytes, partBytes, version, sourceBinding, expectedRequest: request, toolCoverage });
  for (const [relative, bytes] of partBytes) await atomicWrite('assets/data/' + relative, bytes);
  for (const old of await readdir(path.join(ROOT, PART_DIRECTORY))) if (old.endsWith('.json') && !partBytes.has('horizon-2031/' + old)) await rm(path.join(ROOT, PART_DIRECTORY, old));
  await atomicWrite(MANIFEST_PATH, manifestBytes);
  await atomicWrite(VERSION_PATH, versionText(version.source, version.metadata, version.manifest));
  return { ...checked, mode: 'generate', manifestSHA256: version.manifest, metadataSHA256, elapsedMs: result.stats.elapsedMs };
}

function selfTest() {
  let passed = 0;
  const request = { startDate: '2026-10-30', endDate: '2026-10-30', cases: [{ id: 'fixture', label: 'Fixture', lat: 0, lon: 0, timeZone: 'UTC', sampleTime: '12:00', system: 'regiomontanus', disambiguation: 'reject' }], purposeIds: ['fixture'], mode: 'optimized', includeAstronomy: true, includeObservances: true };
  const row = { date: request.startDate, caseId: 'fixture', status: 'available', sampleUTC: '2026-10-30T12:00:00Z', calendars: Array.from({ length: 13 }, (_, i) => ({ id: String(i), status: 'available' })), purposeResults: [{ id: 'fixture', score: 100, scoreNumerator: 1, scoreDenominator: 1, rankable: true, observed: 1, total: 1, missing: [] }], observanceIds: [] };
  const casePart = { case: { id: 'fixture', label: 'Fixture', observer: { lat: 0, lon: 0, timeZone: 'UTC', system: 'regiomontanus' }, sampleTime: '12:00', disambiguation: 'reject', rows: [row] }, observances: [] };
  const astronomy = { events: [], coverage: [], window: { startUTC: '2026-10-30T00:00:00Z', endUTC: '2026-10-31T00:00:00Z' } };
  const sourceBinding = { algorithm: 'fixture', files: [{ path: 'fixture.js', sha256: digest('fixture') }] }; sourceBinding.sha256 = jsonDigest(sourceBinding.files);
  const toolCoverage = { tools: [], references: [] };
  const metadata = { counts: { days: 1, cases: 1, totalSamples: 1, processedSamples: 1, availableSamples: 1, unavailableSamples: 0, calendarRows: 13, availableCalendarRows: 13, profileResults: 1, rankableProfileResults: 1, observanceRows: 0, uniqueObservances: 0, eventCount: 0, truncated: false }, sources: [], coverage: {}, provenance: { runtime: { environment: 'node', node: process.versions.node, icu: process.versions.icu }, generatedAt: '2026-10-30T00:00:00Z', privateBirthIncluded: false, modelUsed: false } };
  function fixture(edit) {
    const c = clone(casePart), a = clone(astronomy), m = clone(metadata); edit?.(c, a, m);
    const partBytes = new Map([['horizon-2031/case-fixture.json', compact(c)], ['horizon-2031/astronomy.json', compact(a)]]);
    const parts = [...partBytes].map(([relative, bytes]) => ({ id: path.basename(relative, '.json'), path: relative, sha256: digest(bytes), bytes: bytes.length }));
    const version = { source: sourceBinding.sha256, metadata: jsonDigest(m) }, manifest = { kind: 'event-horizon-preset', schemaVersion: 1, datasetId: `horizon-2031-${version.source.slice(0,12)}-${version.metadata.slice(0,12)}`, request, sourceBinding, parts, metadata: m, catalogueHashes: catalogueHashes(m, toolCoverage) };
    const manifestBytes = compact(manifest); version.manifest = digest(manifestBytes);
    return { manifestBytes, partBytes, version, sourceBinding, expectedRequest: request, toolCoverage };
  }
  assert.equal(verifyHorizonBundle(fixture()).pass, true); passed++;
  const corrupt = fixture(); corrupt.partBytes.get('horizon-2031/astronomy.json')[0] = 32; assert.throws(() => verifyHorizonBundle(corrupt), /checksum/); passed++;
  const wrongMetadata = fixture(); wrongMetadata.version.metadata = digest('other'); assert.throws(() => verifyHorizonBundle(wrongMetadata), /metadata/); passed++;
  const wrongManifest = fixture(); wrongManifest.manifestBytes = Buffer.concat([wrongManifest.manifestBytes, Buffer.from(' ')]); assert.throws(() => verifyHorizonBundle(wrongManifest), /manifest bytes/); passed++;
  for (const mutation of [c => c.case.rows.pop(), c => c.case.rows[0].calendars.pop(), c => c.case.rows[0].purposeResults.pop(), c => c.case.rows[0].purposeResults[0].score = null, c => c.case.observer.timeZone = 'Europe/London', c => c.observances.push({ id: 'wrong::id', originId: 'id', caseId: 'wrong', date: request.startDate }), (c,a,m) => m.counts.truncated = true]) { assert.throws(() => verifyHorizonBundle(fixture(mutation))); passed++; }
  const parsed = readVersionText(versionText(digest('s'), digest('m'), digest('b'))); assert.equal(parsed.source, digest('s')); passed++;
  const binding = collectHorizonSourceBinding(); assert.ok(binding.files.length > 1 && !binding.files.some(f => f.path === VERSION_PATH)); assert.equal(binding.sha256, jsonDigest(binding.files)); passed++;
  return { pass: true, mode: 'self-test', checks: passed, sourceFiles: binding.files.length, note: 'Synthetic integrity fixtures and actual static source graph only; no astronomical data generation or remote requests.' };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || args.some(a => !['--check', '--graph', '--self-test'].includes(a))) fail('Usage: node scripts/generate-horizon-preset.mjs [--check|--graph|--self-test]');
  if (args[0] === '--graph') return collectHorizonSourceBinding();
  if (args[0] === '--self-test') return selfTest();
  if (args[0] === '--check') return { ...(await checkPreset()), mode: 'check', recalculated: false };
  return generatePreset();
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().then(result => process.stdout.write(JSON.stringify(result, null, 2) + '\n')).catch(error => { process.stderr.write('Horizon preset: ' + error.message + '\n'); process.exitCode = 1; });
}
